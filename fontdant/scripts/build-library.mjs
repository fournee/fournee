// Measures every family in fonts/<id>/ and writes fonts/library.json: the font entries
// (metrics, files, axes, weights, licence) plus the system fallbacks' metrics.
//   node scripts/build-library.mjs
// Inputs: fonts/library-source.json, fonts/<id>/source.json + files (from fetch-library.mjs).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { metricsFromFile, makeEntry } from '../src/metrics.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(root, 'fonts', 'library-source.json'), 'utf8'));
const entries = {};
for (const fam of src.families) {
  const dir = join(root, 'fonts', fam.id);
  const sj = JSON.parse(readFileSync(join(dir, 'source.json'), 'utf8'));
  // measure the variable file, or the 400 (else first) static file; keep per-file metrics for statics too
  const uprights = sj.files.filter((f) => (f.style || 'normal') !== 'italic');
  const main = uprights.find((f) => f.weight === '400') || uprights[0];
  const m = metricsFromFile(join(dir, main.file));
  const perFile = sj.files.map((f) => ({ ...f, style: f.style || 'normal', from: undefined, metrics: f === main ? undefined : pickVertical(metricsFromFile(join(dir, f.file))) }));
  const licText = existsSync(join(dir, 'LICENSE.txt')) ? readFileSync(join(dir, 'LICENSE.txt'), 'utf8') : '';
  const rfn = /with Reserved Font Names?/i.test(licText.split('\n').slice(0, 12).join('\n'));
  const category = sj.category === 'Monospace' ? 'mono' : /Serif/.test(sj.category) && sj.category !== 'Sans Serif' ? 'serif' : sj.category === 'Display' ? 'display' : 'sans';
  entries[fam.id] = makeEntry({
    id: fam.id, family: fam.family, shelf: fam.shelf, slots: src.shelves[fam.shelf].slots, lucky: !!fam.lucky, category, note: fam.note,
    provider: 'google-fonts (self-hosted copy)', metrics: m,
    files: perFile.map((f) => ({ file: f.file, weight: f.weight, style: f.style, unicodeRange: f.unicodeRange, bytes: f.bytes, metrics: f.metrics })),
    licence: {
      id: sj.licence.id, licensor: sj.licence.designer || (sj.designers || []).join(', '), licensee: 'n/a (open)', uses: ['web', 'desktop', 'app'], domains: 'any', cap: null,
      self_host: 'allowed', modify: { subset: true, convert: true, metric_override_css: 'allowed', rename_required: rfn }, reserved_font_name: rfn ? fam.family : null,
      term: { type: 'perpetual' }, proof: sj.licence.source, checked: sj.fetched.slice(0, 10),
    },
  });
}

// System fallbacks are measured from the font files where they exist (Windows). Elsewhere (macOS, Linux, CI) the
// metrics already measured and committed in fonts/library.json are kept: they're fixed properties of those fonts.
const libPath = join(root, 'fonts', 'library.json');
const previous = existsSync(libPath) ? (JSON.parse(readFileSync(libPath, 'utf8')).systemFallbacks || {}) : {};
const systemFallbacks = {};
for (const [k, fb] of Object.entries(src.systemFallbacks)) {
  if (k === 'about') continue;
  if (!existsSync(fb.file)) {
    if (previous[k]) { systemFallbacks[k] = previous[k]; continue; }
    console.warn(`!! system fallback ${fb.family}: ${fb.file} not found and no committed metrics; leaving it out`); continue;
  }
  const m = metricsFromFile(fb.file);
  systemFallbacks[k] = { family: fb.family, local: fb.local, localItalic: fb.localItalic || [], metrics: m, measuredOn: 'this machine (Windows 11)' };
}

const lib = { version: '0.1.0', about: 'Generated by scripts/build-library.mjs from fonts/library-source.json and the fetched files; do not edit. Metrics are font units unless named ratios.', defaultLook: src.defaultLook, shelves: src.shelves, fonts: entries, systemFallbacks };   // no build timestamp: the output is reproducible, so a rebuild never dirties the repo
writeFileSync(join(root, 'fonts', 'library.json'), JSON.stringify(lib, null, 2));

const inter = entries.inter.metrics.ratios;
const n = Object.keys(entries).length, disagree = Object.values(entries).filter((e) => e.metrics.metricTablesDisagree).map((e) => e.id);
const withItalics = Object.values(entries).filter((e) => e.italics.kind !== 'none').length;
console.log(`library.json: ${n} fonts (${withItalics} with italics), ${Object.keys(systemFallbacks).length} system fallbacks; Inter cap ${inter.cap} x ${inter.x} xWidthAvg ${inter.xWidthAvg}; hhea≠typo in ${disagree.length}: ${disagree.join(', ') || 'none'}`);

function pickVertical(m) { return { hhea: m.hhea, typo: m.typo, win: m.win, capHeight: m.capHeight, xHeight: m.xHeight, xWidthAvg: m.xWidthAvg }; }
