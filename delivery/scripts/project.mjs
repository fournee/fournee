// Phase 7: a project's type from its Fournée recipe, as files the project commits (so it builds without Fournée).
//   node delivery/scripts/project.mjs <recipe.json> <out dir> [--base-url ./fonts] [--client-fonts <dir>] [--no-copy] [--display block]
// Writes into <out dir>:
//   fontdant.css    fontdant's base stylesheet (roles, steps, modes, role classes)
//   mise-type.css   the recipe's look: @font-face aliases + metric-matched fallbacks, :root faces / dials / role
//                   overrides, and the project's extension roles (variables + .fd-<name> classes)
//   fonts/<id>/     the font files the look uses: library fonts from Fournée, client fonts from --client-fonts/<id>/
//   recipe.json     the recipe, as applied (the source of truth stays the recipe the project keeps)
// --base-url is how mise-type.css refers to fonts/ (default ./fonts, i.e. beside it, for bundlers that hash assets).
// --no-copy: the project already serves the font files at --base-url (e.g. a site's synced /fonts/library), so fonts/
// is not written; a client font's files then carry their own `src` in the recipe.
// --display block|swap|fallback|optional: font-display for every face, instead of each slot's default (optional
// for display/text: no jump on the web). A desktop app whose fonts are local files wants block: the font is ready
// almost at once, and optional could skip it on a cold start and show the stand-in.
// Prints the <html> attributes the page needs (data-fd-mode) and the font files copied.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const mise = join(here, '..', '..');
const require = createRequire(import.meta.url);

export function projectType(recipe, outDir, opts = {}) {
  const M = require('../dist/mise.js');
  const E = globalThis.FontdantEmit, F = globalThis.FontdantFonts;
  const r = M.clean(recipe), base = opts.baseUrl || './fonts';
  // Git Bash (MSYS) rewrites a POSIX-looking argument such as /fonts into C:/Program Files/Git/fonts, and the
  // CSS would then point every font at Git's install folder. A base URL is never a Windows path.
  if (/^[A-Za-z]:[\\/]/.test(base)) throw new Error(`--base-url ${base} is a Windows path${/Git[\\/]/.test(base) ? ' (Git Bash rewrote it: run with MSYS_NO_PATHCONV=1)' : ''}; pass a URL such as /fonts or ./fonts`);
  mkdirSync(opts.noCopy ? outDir : join(outDir, 'fonts'), { recursive: true });
  if (opts.display && !/^(auto|block|swap|fallback|optional)$/.test(opts.display)) throw new Error(`--display ${opts.display}: use block, swap, fallback or optional`);
  const css = E.css(r.fontdant, { baseUrl: base, display: opts.display });
  const attrs = E.head(r.fontdant, { baseUrl: base }).htmlAttrs;
  const banner = `/* ${r.name}: the Fournée type look. Generated by fournee/delivery/scripts/project.mjs from recipe.json; do not edit, re-run it. */\n`;
  writeFileSync(join(outDir, 'mise-type.css'), banner + css + '\n');
  copyFileSync(join(mise, 'fontdant', 'dist', 'fontdant.css'), join(outDir, 'fontdant.css'));
  writeFileSync(join(outDir, 'recipe.json'), JSON.stringify(recipe, null, 2) + '\n');
  const copied = [];
  for (const f of M.fontFiles(r, { baseUrl: base })) {
    if (f.inline || f.external || opts.noCopy) continue;
    const lib = join(mise, 'fontdant', 'fonts', f.id, f.file);
    const own = opts.clientFonts ? join(opts.clientFonts, f.id, f.file) : null;
    const src = F.isClient(f.id) ? own : lib;
    if (!src || !existsSync(src)) throw new Error(`${f.id}/${f.file}: not found${F.isClient(f.id) ? ' (client font: pass --client-fonts <dir> with <dir>/' + f.id + '/)' : ''}`);
    mkdirSync(join(outDir, 'fonts', f.id), { recursive: true });
    const dest = join(outDir, 'fonts', f.id, f.file), same = resolve(src) === resolve(dest);   // re-run with the project's own fonts/ as the source
    if (!same) copyFileSync(src, dest);
    copied.push(`${f.id}/${f.file}`);
    const dir = dirname(src);
    if (!same) for (const extra of readdirSync(dir)) if (/^(LICEN[CS]E|OFL)/i.test(extra)) copyFileSync(join(dir, extra), join(outDir, 'fonts', f.id, extra));
  }
  return { htmlAttrs: attrs, copied, css };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args.splice(i, 2)[1] : undefined; };
  const noCopy = args.includes('--no-copy'); if (noCopy) args.splice(args.indexOf('--no-copy'), 1);
  const baseUrl = flag('--base-url'), clientFonts = flag('--client-fonts'), display = flag('--display');
  const [recipePath, outDir] = args;
  if (!recipePath || !outDir) { console.error('usage: node delivery/scripts/project.mjs <recipe.json> <out dir> [--base-url ./fonts] [--client-fonts <dir>] [--no-copy] [--display block|swap|fallback|optional]'); process.exit(2); }
  const out = projectType(JSON.parse(readFileSync(recipePath, 'utf8')), outDir, { baseUrl, clientFonts, noCopy, display });
  console.log(`${outDir}: fontdant.css, mise-type.css, ${noCopy ? 'fonts not copied (--no-copy)' : `${out.copied.length} font files (${out.copied.join(', ')})`}`);
  console.log(`<html> needs: ${Object.entries(out.htmlAttrs).map(([k, v]) => `${k}="${v}"`).join(' ') || '(nothing)'}`);
}
