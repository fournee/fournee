// Generates dist/frosting.css and dist/tokens.js from tokens.json.
// Usage: node scripts/build.mjs [--prefix=app]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'));
const prefixArg = process.argv.find((a) => a.startsWith('--prefix='));
const prefix = prefixArg ? prefixArg.slice('--prefix='.length) : tokens.prefix;
const v = (role, key) => `  --${prefix}-${role.name}: ${role[key]};`;

const byGroup = Object.keys(tokens.groups).map((g) =>
  [`  /* ── ${g} ── ${tokens.groups[g]} */`, ...tokens.roles.filter((r) => r.group === g).map((r) => v(r, 'light'))].join('\n'));
const dark = tokens.roles.map((r) => v(r, 'dark')).join('\n');
const derived = Object.entries(tokens.derived).filter(([k]) => k !== 'about')
  .map(([k, val]) => `  --${prefix}-${k}: ${val.replaceAll('{p}', prefix)};`).join('\n');

const css = `/* frosting tokens v${tokens.version} — generated from tokens.json by scripts/build.mjs; do not edit.
   Light defaults on :root; dark defaults under prefers-color-scheme: dark (unless data-theme="light")
   and under an explicit data-theme="dark". A look overrides any of these with setProperty. */
:root {
${byGroup.join('\n')}

  /* ── derived ── ${tokens.derived.about} */
${derived}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark}
  }
}
:root[data-theme="dark"] {
${dark}
}
/* Gradient fills (src/fills.js): a look may set --${prefix}-<role>-fill on top of a role's solid colour. Paint
   background-color: var(--${prefix}-<role>); background-image: var(--${prefix}-<role>-fill, none).
   Forced colours, more contrast and print get the solid roles: every fill is switched off here, beating a
   look's inline values (!important). */
@media (forced-colors: active), (prefers-contrast: more), print {
  :root, :root * {
${tokens.roles.map((r) => `    --${prefix}-${r.name}-fill: none !important;`).join('\n')}
  }
}
`;

const pick = (key) => Object.fromEntries(tokens.roles.map((r) => [r.name, r[key]]));
const api = { version: tokens.version, prefix, groups: tokens.groups, roles: tokens.roles, contracts: tokens.contracts, light: pick('light'), dark: pick('dark') };
const js = `/* frosting tokens v${tokens.version} — generated from tokens.json; do not edit. Plain script: window.FrostingTokens, or require()-able. */
(function (root) {
  var api = ${JSON.stringify(api, null, 2)};
  root.FrostingTokens = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
`;

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'frosting.css'), css);
writeFileSync(join(root, 'dist', 'tokens.js'), js);
// dist/store.js: kitchen's store engine + frosting's face on it, one file, so consumers that load a single
// store.js (the catalog, a project's vendored copy) keep working unchanged after the Fournée phase 1 lift.
const kitchenStore = readFileSync(join(root, '..', 'kitchen', 'src', 'store.js'), 'utf8');
const frostingStore = readFileSync(join(root, 'src', 'store.js'), 'utf8');
writeFileSync(join(root, 'dist', 'store.js'), `/* frosting store — generated by scripts/build.mjs from kitchen/src/store.js + frosting/src/store.js; do not edit. */\n${kitchenStore}\n${frostingStore}`);
console.log(`built dist/frosting.css and dist/tokens.js (prefix --${prefix}-, ${tokens.roles.length} roles, ${tokens.contracts.length} contracts)`);
